package com.example.calculatorkotlin

class Operation() {

    fun add(a: Double, b: Double): Double {
        return a+b
    }

    fun subtraction(a: Double, b: Double): Double {
        return a-b
    }

    fun divisio(a: Double, b: Double): Double {
        return a/b
    }

    fun multiplication(a: Double, b: Double): Double {
        return a*b
    }
}